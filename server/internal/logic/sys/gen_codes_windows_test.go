func mapGenerationFile(t *testing.T, path string) func() {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	mapping, err := windows.CreateFileMapping(windows.Handle(f.Fd()), nil, windows.PAGE_READONLY, 0, 0, nil)
	if err != nil {
		_ = f.Close()
		t.Fatal(err)
	}
	view, err := windows.MapViewOfFile(mapping, windows.FILE_MAP_READ, 0, 0, 0)
	if err != nil {
		_ = windows.CloseHandle(mapping)
		_ = f.Close()
		t.Fatal(err)
	}
	var once sync.Once
	release := func() {
		once.Do(func() {
			_ = windows.UnmapViewOfFile(view)
			_ = windows.CloseHandle(mapping)
			_ = f.Close()
		})
	}
	t.Cleanup(release)
	return release
}

// Windows 编译器或编辑器短暂映射旧服务文件时，等待释放后发布完整的新文件。
func TestRefreshBuildServicesReplacesMappedFile(t *testing.T) {
	t.Chdir(t.TempDir())
	write := func(path, content string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/mappedservice\n\ngo 1.24.4\n")
	write("internal/logic/sys/active.go", "package sys\n\ntype sActive struct{}\n\nfunc (s *sActive) Run() {}\n")
	write("internal/service/sys.go", "// Code generated by test. DO NOT EDIT.\npackage service\n\ntype Old interface{}\n")
	release := mapGenerationFile(t, "internal/service/sys.go")
	// 编译器读取期间占用映射，完成后释放；服务生成应等待而不是留下半成品。
	released := make(chan struct{})
	go func() {
		defer close(released)
		time.Sleep(500 * time.Millisecond)
		release()
	}()
	defer func() { <-released }()
	if err := NewSysGenCodes().refreshBuildServices(context.Background(), &entity.SysGenCodes{}, model.GenerateAppCrudTemplate{}); err != nil {
		t.Fatalf("generation failed while an existing service file was mapped: %v", err)
	}
	content, err := os.ReadFile("internal/service/sys.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(content), "IActive interface") {
		t.Fatalf("new service was not published: %s", content)
	}
}

func TestPublishBuildPreviewPreservesLockedOriginal(t *testing.T) {
	disableGenCodesFileLogs(t)
	path := filepath.Join(t.TempDir(), "index.vue")
	const old = "original generated view must remain intact"
	if err := os.WriteFile(path, []byte(old), 0644); err != nil {
		t.Fatal(err)
	}
	mapGenerationFile(t, path)
	preview := &sysin.GenCodesPreviewModel{Views: map[string]*sysin.GenFile{
		"web.index.vue": {Path: path, Content: "replacement", Meth: consts.GenCodesBuildMethCover},
	}}
	err := NewSysGenCodes().publishBuildPreview(context.Background(), 52, preview,
		func(context.Context) error { return nil },
		func(context.Context) error {
			t.Error("service generation ran after file publication failed")
			return nil
		})
	if err == nil {
		t.Fatal("publishing a permanently mapped view should fail")
	}
	content, readErr := os.ReadFile(path)
	if readErr != nil || string(content) != old {
		t.Fatalf("original view damaged: content=%q err=%v", content, readErr)
	}
}

func TestPublishGeneratedFilePreservesLockedOriginal(t *testing.T) {
	t.Chdir(t.TempDir())
	const path, old = "sys.go", "original service must remain intact"
	if err := os.WriteFile(path, []byte(old), 0644); err != nil {
		t.Fatal(err)
	}
	mapGenerationFile(t, path)
	// 相同内容应直接跳过；永久占用导致发布失败时必须保留原文件并返回错误。
	if err := publishGeneratedFile(path, []byte(old)); err != nil {
		t.Fatal(err)
	}
	if err := publishGeneratedFile(path, []byte("replacement")); err == nil {
		t.Fatal("publishing a permanently mapped file should fail")
	}
	content, err := os.ReadFile(path)
	if err != nil || string(content) != old {
		t.Fatalf("original file damaged after failed publication: content=%q err=%v", content, err)
	}
	files, err := filepath.Glob(".hotgo-publish-*")
	if err != nil || len(files) != 0 {
		t.Fatalf("temporary publication files leaked: %v %v", files, err)
	}
}
