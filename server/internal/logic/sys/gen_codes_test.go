package sys

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"hotgo/internal/model"
	"hotgo/internal/model/entity"
)

func TestRefreshBuildServices(t *testing.T) {
	for _, addon := range []bool{false, true} {
		name := "main"
		if addon {
			name = "addon"
		}
		t.Run(name, func(t *testing.T) {
			t.Chdir(t.TempDir())

			srcFolder := "internal/logic"
			dstFolder := "internal/service"
			unrelatedFile := "addons/example/service/unrelated.go"
			if addon {
				srcFolder = "addons/example/logic"
				dstFolder = "addons/example/service"
				unrelatedFile = "internal/service/unrelated.go"
			}
			writeFile := func(path, content string) {
				t.Helper()
				if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(path, []byte(content), 0644); err != nil {
					t.Fatal(err)
				}
			}
			assertFile := func(path, want string) {
				t.Helper()
				content, err := os.ReadFile(path)
				if err != nil {
					t.Fatalf("expected preserved file %s: %v", path, err)
				}
				if !strings.Contains(string(content), want) {
					t.Fatalf("%s does not contain %q: %s", path, want, content)
				}
			}
			assertMissing := func(path string) {
				t.Helper()
				if _, err := os.Stat(path); !os.IsNotExist(err) {
					t.Fatalf("expected obsolete service %s to be removed, stat error: %v", path, err)
				}
			}

			writeFile("go.mod", "module example.com/servicecleanup\n\ngo 1.24.4\n")
			writeFile(srcFolder+"/active/active.go", "package active\n\ntype sActive struct{}\n\nfunc (s *sActive) Run() string { return \"active\" }\n")
			writeFile(srcFolder+"/other/other.go", "package other\n\ntype sOther struct{}\n\nfunc (s *sOther) Run() string { return \"other\" }\n")
			writeFile(srcFolder+"/manual/manual.go", "package manual\n\ntype sManual struct{}\n\nfunc (s *sManual) Run() {}\n")
			const manualContent = "package service\n\n// Manually maintained service.\ntype Manual interface {\n\tRun()\n}\n"
			writeFile(dstFolder+"/manual.go", manualContent)
			writeFile(dstFolder+"/obsolete.go", "// Code generated by test. DO NOT EDIT.\npackage service\n")
			writeFile(unrelatedFile, "// Code generated by test. DO NOT EDIT.\npackage service\n\n// Unrelated module.\n")

			service := NewSysGenCodes()
			record := &entity.SysGenCodes{AddonName: "example"}
			template := model.GenerateAppCrudTemplate{IsAddon: addon}
			for pass := 0; pass < 2; pass++ {
				if err := service.refreshBuildServices(context.Background(), record, template); err != nil {
					t.Fatal(err)
				}
				assertFile(dstFolder+"/other.go", "IOther interface")
				assertFile(dstFolder+"/manual.go", manualContent)
				assertFile(unrelatedFile, "Unrelated module.")
				assertMissing(dstFolder + "/obsolete.go")
				if pass == 0 {
					assertFile(dstFolder+"/active.go", "IActive interface")
					if err := os.Remove(srcFolder + "/active/active.go"); err != nil {
						t.Fatal(err)
					}
				} else {
					assertMissing(dstFolder + "/active.go")
				}
			}
		})
	}
}
